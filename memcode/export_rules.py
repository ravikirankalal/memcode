"""Write memcode's memory into an instruction file another agent already reads (Phase 4: scale out).

Agents without memcode's hooks still load a project instructions file at session start. `sync` renders the same
block Claude Code gets at SessionStart (rules, map, notes; same framing and token cap) into one of:

  block mode   a marked block inside an existing file (e.g. AGENTS.md); text outside the markers is never touched
  file mode    a file memcode owns outright (e.g. .cursor/rules/memcode.mdc), added to .git/info/exclude so personal
               memory is not committed by accident

Re-running replaces the previous block or file; an empty store removes it. Per-prompt retrieval is not available
this way (a static file cannot see the prompt); the MCP tool memory_search covers that where MCP is supported.
"""
from __future__ import annotations

import os
import subprocess

from . import pinned

START = "<!-- memcode:start (generated by memcode; edits here are overwritten: `python3 -m memcode sync-rules`) -->"
END = "<!-- memcode:end -->"


def render(con, root: str, token_cap: int = 1500) -> str:
    return pinned.render_pinned(con, root, token_cap=token_cap)


def _replace_block(existing: str, body: str) -> str:
    """existing text with the memcode block replaced, appended, or (body == '') removed."""
    i, j = existing.find(START), existing.find(END)
    block = f"{START}\n{body}\n{END}\n" if body else ""
    if i != -1 and j != -1 and j > i:
        head, tail = existing[:i], existing[j + len(END):].lstrip("\n")
        out = head + block + tail
    elif body:
        sep = "" if not existing or existing.endswith("\n\n") else ("\n" if existing.endswith("\n") else "\n\n")
        out = existing + sep + block
    else:
        out = existing
    return out


def write_block(path: str, body: str) -> bool:
    """Update the memcode block in `path`. Returns True if the file changed."""
    try:
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
    except FileNotFoundError:
        old = ""
    new = _replace_block(old, body)
    if new == old:
        return False
    if not new.strip():
        os.remove(path)
        return True
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(new)
    return True


def write_file(path: str, body: str, header: str = "") -> bool:
    """Own `path` outright: write header + body, or delete it when body is empty. Returns True if it changed."""
    new = (header + body + "\n") if body else None
    try:
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
    except FileNotFoundError:
        old = None
    if new == old:
        return False
    if new is None:
        os.remove(path)
        return True
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(new)
    return True


def git_exclude(root: str, rel: str) -> None:
    """Best effort: add `rel` to .git/info/exclude (never to the shared .gitignore)."""
    try:
        r = subprocess.run(["git", "-C", root, "rev-parse", "--git-path", "info/exclude"],
                           capture_output=True, text=True, timeout=5)
        if r.returncode != 0:
            return
        p = r.stdout.strip()
        p = p if os.path.isabs(p) else os.path.join(root, p)
        lines = []
        if os.path.exists(p):
            with open(p, encoding="utf-8") as fh:
                lines = fh.read().splitlines()
        if "/" + rel not in lines:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "a", encoding="utf-8") as fh:
                fh.write(("" if not lines or lines[-1] == "" else "\n") + "/" + rel + "\n")
    except (OSError, subprocess.SubprocessError):
        pass


# target name -> (repo-relative path, mode, header for file mode)
TARGETS = {
    "agents": ("AGENTS.md", "block", ""),
}


def sync(con, root: str, targets: list[str]) -> dict[str, bool]:
    """Render once and write every target. Returns {target: changed}."""
    body = render(con, root)
    out = {}
    for t in targets:
        if t not in TARGETS:
            raise ValueError(f"unknown target {t!r} (known: {', '.join(sorted(TARGETS))})")
        rel, mode, header = TARGETS[t]
        path = os.path.join(root, rel)
        if mode == "block":
            out[t] = write_block(path, body)
        else:
            out[t] = write_file(path, body, header)
            git_exclude(root, rel)
    return out
